// @ts-check
/**
 * Brand Commerce Platform — ESLint 9 flat config (ESM).
 *
 * Monorepo layout: NestJS API (apps/api) + Next.js storefront (apps/storefront)
 * + shared packages (packages/*). Linting is deliberately non type-aware (no
 * projectService / tsconfig wiring) to keep `npm run lint` fast; the TypeScript
 * compiler and the test suites cover the type-level guarantees.
 *
 * Run from the repo root: `npm run lint` (= `eslint .`).
 */
import eslint from '@eslint/js';
import tseslint from 'typescript-eslint';

/**
 * Shared globals, declared inline so no extra dependency (e.g. `globals`) is
 * needed.
 * - Node globals cover the API, Next.js server components and next.config.mjs.
 * - Browser globals cover storefront client components (e.g. app/error.tsx).
 * Note: `no-undef` is switched off for TS/TSX files by typescript-eslint's
 * "eslint-recommended" compatibility layer (the TS compiler catches that
 * instead), so these globals mainly matter for plain .mjs/.js files.
 */
const sharedGlobals = {
  // Node
  process: 'readonly',
  console: 'readonly',
  // Browser
  window: 'readonly',
  document: 'readonly',
  localStorage: 'readonly',
  navigator: 'readonly',
};

export default tseslint.config(
  // 1. Global ignores — generated, vendored or non-JavaScript files.
  {
    ignores: [
      '**/node_modules/**',
      '**/dist/**',
      '**/.next/**',
      '**/build/**',
      '**/coverage/**',
      '**/*.config.js',
      '**/jest.config.js',
      // Prisma DSL folder (seed.ts intentionally uses console.log).
      'packages/database/prisma/**',
      // Shared config package — JSON only.
      'packages/config/**',
      '**/.mimosa/**',
      'install.log',
      // Next.js-generated file (regenerated by `next dev`/`next build`).
      // It contains `/// <reference path=...>` directives which
      // @typescript-eslint/triple-slash-reference (default: path 'never')
      // rejects — a generated file we must not edit, so it is ignored.
      '**/next-env.d.ts',
    ],
  },

  // 2. Base: JS recommended for every lintable file + shared globals.
  eslint.configs.recommended,
  {
    languageOptions: {
      globals: sharedGlobals,
    },
  },

  // 3. TypeScript: typescript-eslint "recommended", non type-aware.
  //    This bundles:
  //    - the @typescript-eslint parser + plugin wiring,
  //    - the "eslint-recommended" compatibility layer for TS/TSX files
  //      (e.g. core `no-undef` off — the compiler owns that check),
  //    - the recommended @typescript-eslint rules.
  //    No React plugin is installed; typescript-eslint never emits
  //    `react/react-in-jsx-scope`, so no React-specific disables are needed.
  ...tseslint.configs.recommended,

  // 4. Storefront (Next.js App Router): enable JSX parsing for TSX/JSX.
  {
    files: ['apps/storefront/**/*.{ts,tsx}'],
    languageOptions: {
      parserOptions: {
        ecmaFeatures: { jsx: true },
      },
    },
  },

  // 5. Strict TypeScript policy for this codebase.
  {
    files: ['**/*.ts', '**/*.tsx'],
    rules: {
      // `any` is banned outright — shared contracts/domain types are precise.
      '@typescript-eslint/no-explicit-any': 'error',
      // Allow the `_` convention for intentionally unused arguments/variables
      // (e.g. unused NestJS pipe metadata parameters in custom pipes).
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
    },
  },
);
